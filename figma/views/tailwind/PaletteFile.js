import { writeFile } from "fs/promises";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
export const PALETTE_PATH = join(__dirname, "../../../styles/colors.css");

/**
 * Renders the palette as a Tailwind v4 @theme block. Deterministic, and already
 * in the form Prettier writes, so a sync needs no formatting pass.
 */
export function render(palette, { source }) {
  const rows = palette.map(({ name, hex }) => `  --color-${name}: ${hex};`);
  return `/** @format */
/**
 * @fileoverview Colour palette generated by the Figma sync. Do not edit by hand;
 * change the colour variable in Figma and run npm run build:design.
 * @source ${source}
 */

@theme {
${rows.join("\n")}
}
`;
}

export async function write(palette, meta) {
  await writeFile(PALETTE_PATH, render(palette, meta), "utf8");
}
