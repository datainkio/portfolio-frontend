/** @format */

import assert from "node:assert/strict";
import {
  extractPalette,
  PaletteService,
} from "../../figma/services/PaletteService.js";
import { render } from "../../figma/views/tailwind/PaletteFile.js";

// Variables follow extractVariables' output for the library's Color collection.
const colour = (name, color) => [
  name,
  { name, resolvedType: "COLOR", valuesByMode: { "2:0": color } },
];
const library = Object.fromEntries([
  colour("semantic/fail", { r: 0.8627, g: 0.2588, b: 0.102, a: 1 }),
  colour("accent/500", {
    r: 0.9843137264251709,
    g: 0.7647058963775635,
    b: 0.04313725605607033,
    a: 1,
  }),
  colour("accent/50", { r: 1, g: 0.996, b: 0.918, a: 1 }),
  colour("base/white", { r: 1, g: 1, b: 1, a: 1 }),
  colour("base/black", { r: 0, g: 0, b: 0, a: 1 }),
  [
    "spacing/4",
    { name: "spacing/4", resolvedType: "FLOAT", valuesByMode: { "2:1": 16 } },
  ],
]);
const palette = extractPalette(library);

let passed = 0;
const test = async (name, fn) => {
  await fn();
  passed += 1;
  console.log(`  ok - ${name}`);
};

await test("colour variables become palette entries, sorted as before", () => {
  assert.deepEqual(palette, [
    { name: "accent-50", hex: "#fffeea" },
    { name: "accent-500", hex: "#fbc30b" },
    { name: "semantic-fail", hex: "#dc421a" },
  ]);
});

await test("Tailwind's built-in white and black are left out", () => {
  assert.ok(!palette.some(({ name }) => name.startsWith("base")));
});

await test("a translucent colour keeps its alpha as eight-digit hex", () => {
  const [entry] = extractPalette(
    Object.fromEntries([colour("neutral/950", { r: 0, g: 0, b: 0, a: 0.5 })]),
  );
  assert.equal(entry.hex, "#00000080");
});

await test("render writes a deterministic @theme block in Prettier's form", () => {
  assert.equal(
    render(palette.slice(0, 2), { source: "Figma file x, version 1" }),
    `/** @format */
/**
 * @fileoverview Colour palette generated by the Figma sync. Do not edit by hand;
 * change the colour variable in Figma and run npm run build:design.
 * @source Figma file x, version 1
 */

@theme {
  --color-accent-50: #fffeea;
  --color-accent-500: #fbc30b;
}
`,
  );
});

await test("no colour variables throws before anything is written", async () => {
  await assert.rejects(
    new PaletteService().write({}, { source: "test" }),
    /no colour variables\. styles\/colors\.css was not changed/,
  );
});

console.log(`\nFigma palette: ${passed} passed`);
