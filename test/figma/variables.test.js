import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  extractVariables,
  VariablesService,
} from "../../figma/services/VariablesService.js";

// Node shapes follow a GET /v1/files/:key/nodes response for the library's
// Tokens page, built by figma/generators/tokensPage.js on 2026-11-08.
const COLOR = "VariableCollectionId:2:2";
const TYPE = "VariableCollectionId:2:110";

const alias = (id) => ({ type: "VARIABLE_ALIAS", id });
const meta = (data) => ({
  name: "meta",
  type: "TEXT",
  visible: false,
  characters: JSON.stringify(data),
});
const variableMeta = (id, name, collection, resolvedType) =>
  meta({
    kind: "variable",
    id,
    name,
    key: `key-${id}`,
    variableCollectionId: collection,
    resolvedType,
    description: `${name} token`,
    hiddenFromPublishing: false,
    scopes: resolvedType === "COLOR" ? ["ALL_FILLS", "STROKE_COLOR"] : [],
    codeSyntax: { WEB: `var(--${name.replaceAll("/", "-")})` },
  });
const collectionMeta = (id, name, modeId, variableIds) =>
  meta({
    kind: "collection",
    id,
    name,
    key: `key-${id}`,
    modes: [{ modeId, name: "Value" }],
    defaultModeId: modeId,
    hiddenFromPublishing: false,
    variableIds,
  });

/** `boundId: null` drops the binding, as a detached layer would. */
function colorLayer(id, name, color, { opacity, boundId = id } = {}) {
  const paint = {
    blendMode: "NORMAL",
    type: "SOLID",
    color: { ...color, a: 1 },
  };
  if (opacity !== undefined) paint.opacity = opacity;
  const layer = {
    name: `Color/${name}`,
    type: "FRAME",
    fills: [paint],
    children: [variableMeta(id, name, COLOR, "COLOR")],
  };
  if (boundId) {
    paint.boundVariables = { color: alias(boundId) };
    layer.boundVariables = { fills: [alias(boundId)] };
  }
  return layer;
}
function floatLayer(id, name, itemSpacing, { boundId = id } = {}) {
  const layer = {
    name: `Typography/${name}`,
    type: "FRAME",
    layoutMode: "HORIZONTAL",
    boundVariables: { itemSpacing: alias(boundId) },
    children: [variableMeta(id, name, TYPE, "FLOAT")],
  };
  if (itemSpacing !== undefined) layer.itemSpacing = itemSpacing;
  return layer;
}
function stringLayer(id, name, characters) {
  return {
    name: `Typography/${name}`,
    type: "FRAME",
    children: [
      {
        name: "value",
        type: "TEXT",
        characters,
        boundVariables: { characters: alias(id) },
      },
      variableMeta(id, name, TYPE, "STRING"),
    ],
  };
}

const idOf = (layer) =>
  JSON.parse(layer.children.find((c) => c.name === "meta").characters).id;
const row = (layer) => ({
  name: `Row · ${layer.name}`,
  type: "FRAME",
  children: [
    layer,
    {
      name: "Label",
      type: "FRAME",
      children: [{ name: "Name", type: "TEXT", characters: layer.name }],
    },
  ],
});

function tokensPage(
  colorLayers,
  typeLayers,
  { colorIds = colorLayers.map(idOf), typeIds = typeLayers.map(idOf) } = {},
) {
  const section = (id, name, modeId, layers, ids) => ({
    name,
    type: "FRAME",
    children: [
      { name: "Heading", type: "TEXT", characters: name },
      collectionMeta(id, name, modeId, ids),
      { name: "Grid", type: "FRAME", children: layers.map(row) },
    ],
  });
  return {
    id: "44:2",
    name: "Tokens",
    type: "CANVAS",
    children: [
      {
        name: "Tokens",
        type: "FRAME",
        children: [
          { name: "About", type: "TEXT", characters: "Generated by …" },
          section(COLOR, "Color", "2:0", colorLayers, colorIds),
          section(TYPE, "Typography", "2:3", typeLayers, typeIds),
          {
            name: "Styles",
            type: "FRAME",
            children: [
              row({
                name: "TextStyle/Body/xs",
                type: "TEXT",
                characters: "Aa",
                styles: { text: "3:2" },
              }),
            ],
          },
        ],
      },
    ],
  };
}

const accent = colorLayer("VariableID:2:8", "accent/500", {
  r: 0.98,
  g: 0.76,
  b: 0.04,
});
const snug = floatLayer("VariableID:2:149", "leading/snug", 1.1670000553131104);
const tight = floatLayer(
  "VariableID:2:153",
  "tracking/tight",
  -0.02500000037252903,
);
const screen = floatLayer("VariableID:2:104", "screen/default", undefined);
const display = stringLayer("VariableID:2:113", "font/display", "DRAFT PAPER");
const page = tokensPage([accent], [snug, tight, screen, display]);
const { variables, variableCollections } = extractVariables(page);
const valueOf = (id) => Object.values(variables[id].valuesByMode)[0];

let passed = 0;
const test = async (name, fn) => {
  await fn();
  passed += 1;
  console.log(`  ok - ${name}`);
};

await test("reads every bound layer at any depth, keyed by variable ID", () => {
  assert.deepEqual(Object.keys(variables).sort(), [
    "VariableID:2:104",
    "VariableID:2:113",
    "VariableID:2:149",
    "VariableID:2:153",
    "VariableID:2:8",
  ]);
});

await test("a variable has the Enterprise fields, valued under its collection's mode", () => {
  assert.deepEqual(variables["VariableID:2:8"], {
    id: "VariableID:2:8",
    name: "accent/500",
    key: "key-VariableID:2:8",
    variableCollectionId: COLOR,
    resolvedType: "COLOR",
    valuesByMode: { "2:0": { r: 0.98, g: 0.76, b: 0.04, a: 1 } },
    remote: false,
    description: "accent/500 token",
    hiddenFromPublishing: false,
    scopes: ["ALL_FILLS", "STROKE_COLOR"],
    codeSyntax: { WEB: "var(--accent-500)" },
  });
});

await test("floats keep Figma's precision and sign, and an omitted gap reads as 0", () => {
  assert.deepEqual(variables["VariableID:2:149"].valuesByMode, {
    "2:3": 1.1670000553131104,
  });
  assert.equal(valueOf("VariableID:2:153"), -0.02500000037252903);
  assert.equal(valueOf("VariableID:2:104"), 0);
});

await test("strings come from the bound text", () => {
  assert.equal(valueOf("VariableID:2:113"), "DRAFT PAPER");
});

await test("paint opacity scales a colour's alpha", () => {
  const faded = colorLayer(
    "VariableID:2:9",
    "accent/600",
    { r: 1, g: 0, b: 0 },
    {
      opacity: 0.5,
    },
  );
  const result = extractVariables(tokensPage([faded], []));
  assert.equal(result.variables["VariableID:2:9"].valuesByMode["2:0"].a, 0.5);
});

await test("a collection has the Enterprise fields", () => {
  assert.deepEqual(variableCollections[TYPE], {
    id: TYPE,
    name: "Typography",
    key: `key-${TYPE}`,
    modes: [{ modeId: "2:3", name: "Value" }],
    defaultModeId: "2:3",
    remote: false,
    hiddenFromPublishing: false,
    variableIds: [
      "VariableID:2:149",
      "VariableID:2:153",
      "VariableID:2:104",
      "VariableID:2:113",
    ],
  });
});

await test("a layer that lost its binding fails the run", () => {
  const detached = colorLayer(
    "VariableID:2:8",
    "accent/500",
    { r: 0, g: 0, b: 0 },
    {
      boundId: null,
    },
  );
  assert.throws(
    () => extractVariables(tokensPage([detached], [])),
    /Re-run figma\/generators\/tokensPage\.js[\s\S]*Color\/accent\/500 isn't bound to a variable/,
  );
});

await test("a layer bound to a different variable fails the run", () => {
  const swapped = floatLayer("VariableID:2:149", "leading/snug", 1.5, {
    boundId: "VariableID:9:9",
  });
  assert.throws(
    () => extractVariables(tokensPage([], [swapped])),
    /bound to VariableID:9:9, not VariableID:2:149/,
  );
});

await test("a collection that lists a variable with no layer fails the run", () => {
  assert.throws(
    () =>
      extractVariables(
        tokensPage([], [snug], {
          typeIds: [idOf(snug), "VariableID:2:999"],
        }),
      ),
    /Typography lists VariableID:2:999, but no layer on the page holds it/,
  );
});

const fakeClient = (responses) => {
  const calls = [];
  return {
    calls,
    FILE_ID: "libraryKey",
    fetch: async (endpoint) => {
      calls.push(endpoint);
      return responses(endpoint);
    },
  };
};
const pagesResponse = (pages) => ({
  name: "dataink.io Design System",
  version: "123",
  lastModified: "2026-11-08T12:00:00Z",
  document: { children: pages },
});

await test("write saves the Enterprise response shape, read through two REST calls", async () => {
  const client = fakeClient((endpoint) =>
    endpoint.endsWith("?depth=1")
      ? pagesResponse([
          { id: "0:1", name: "Cover" },
          { id: "44:2", name: "Tokens" },
        ])
      : { nodes: { "44:2": { document: page } } },
  );
  const dir = await mkdtemp(join(tmpdir(), "variables-test-"));
  try {
    const outFile = join(dir, "nested", "variables.local.json");
    const result = await new VariablesService(client).write(outFile);
    const saved = JSON.parse(await readFile(outFile, "utf8"));
    assert.deepEqual(client.calls, [
      "/files/libraryKey?depth=1",
      "/files/libraryKey/nodes?ids=44:2",
    ]);
    assert.deepEqual(result, { outFile, variables: 5, collections: 2 });
    assert.equal(saved.status, 200);
    assert.equal(saved.error, false);
    assert.deepEqual(saved.meta, { variables, variableCollections });
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

await test("fetchTokensPage also returns the file's name and version, for CSS headers", async () => {
  const client = fakeClient((endpoint) =>
    endpoint.endsWith("?depth=1")
      ? pagesResponse([{ id: "44:2", name: "Tokens" }])
      : { nodes: { "44:2": { document: page } } },
  );
  const result = await new VariablesService(client).fetchTokensPage();
  assert.deepEqual(result.file, {
    name: "dataink.io Design System",
    version: "123",
    lastModified: "2026-11-08T12:00:00Z",
  });
  assert.equal(result.page, page);
});

await test("a Tokens page with no generated layers, like the old file's, fails with a hint", () => {
  const oldTokensPage = {
    name: "#️ Tokens",
    type: "CANVAS",
    children: [{ name: "spacing/4", type: "RECTANGLE" }],
  };
  assert.throws(
    () => extractVariables(oldTokensPage),
    /no generated layers\. Check that FIGMA_FILE_ID names the design-system library/,
  );
});

await test("a file with no Tokens page fails with a hint", async () => {
  const client = fakeClient(() =>
    pagesResponse([{ id: "0:1", name: "Cover" }]),
  );
  await assert.rejects(
    new VariablesService(client).fetchTokensPage(),
    /no Tokens page\. Run figma\/generators\/tokensPage\.js first/,
  );
});

await test("a Figma API error is reported, not parsed as a file", async () => {
  const client = fakeClient(() => ({ status: 403, err: "Invalid token" }));
  await assert.rejects(
    new VariablesService(client).fetchTokensPage(),
    /Figma API 403: Invalid token/,
  );
});

